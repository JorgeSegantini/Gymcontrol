  static String paraData(DateTime data) {
    final inicioAno = DateTime(data.year, 1, 1);
    var indice = data.difference(inicioAno).inDays;
    if (_anoBissexto(data.year) && indice >= 59) {
      if (data.month == DateTime.february && data.day == 29) {
        return 'Um dia extra também pode ser um passo a mais.';
      }
      indice -= 1;
    }
    return frases[indice % frases.length];
  }

  static bool _anoBissexto(int ano) {
    return ano % 4 == 0 && (ano % 100 != 0 || ano % 400 == 0);
  }
